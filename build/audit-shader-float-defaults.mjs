const shaderNames = [...new Set([...Object.keys(SHADER), ...Object.keys(FALLBACKS)])].sort();

const OFFICIAL_DEAD_FLOATS = new Set([
  "Card_UR_LensFlare:_Offset",
  "Card_Parallax_Metal:_UseUv2",
  "Card_Parallax_Hologram_UR_New:_DarknessEnabled",
  "Card_Parallax_Hologram_UR_New:_FakeSpecularEnabled",
  "Opaque-Hologram_Tuning:_DiffractionIntensity",
  "Opaque-UR-Oklab:_DarknessEnabled",
]);

let official;
try {
  const stdout = execSync("python build/extract-shader-defaults.py", {
    input: JSON.stringify({ root: shaderRoot, shaders: shaderNames }),
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024,
    stdio: ["pipe", "pipe", "inherit"],
  });
  official = JSON.parse(stdout);
} catch (err) {
  console.error(err.message);
  process.exit(1);
}

const EPS = 1e-6;
const rows = [];
for (const [shader, fallbacks] of Object.entries(FALLBACKS)) {
  const officialFloats = official.found[shader]?.floats || {};
  for (const [name, local] of Object.entries(fallbacks)) {
    const dead = OFFICIAL_DEAD_FLOATS.has(`${shader}:${name}`);
    const officialValue = officialFloats[name];
    const ok = dead || (typeof officialValue === "number" && Math.abs(officialValue - local) <= EPS);
    rows.push({
      ok,
      dead,
      shader,
      name,
      local,
      official: officialValue ?? "(missing)",
      reason: dead ? "official bytecode does not read float" : (ok ? "matches" : "default mismatch"),
    });
  }
}

for (const row of rows.sort((a, b) => a.shader.localeCompare(b.shader) || a.name.localeCompare(b.name))) {
  const mark = row.dead ? "DEAD" : (row.ok ? "OK  " : "BAD ");
  console.log(`${mark} ${row.shader.padEnd(35)} ${row.name.padEnd(28)} local=${String(row.local).padEnd(8)} official=${row.official} ${row.reason}`);
}

const bad = rows.filter((row) => !row.ok);
if (bad.length) {
  console.error(`\n${bad.length} shader float default issue(s) found.`);
  process.exitCode = 1;
}
